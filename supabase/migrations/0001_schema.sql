-- An invoice number is a real-world identifier. Reissuing one to a different
-- client is the failure this constraint exists to make impossible.
create unique index if not exists invoices_number_key on public.invoices (number);

create index if not exists leads_lead_score_idx       on public.leads (lead_score desc);
create index if not exists leads_followup_idx         on public.leads (next_followup_date);
create index if not exists calls_lead_idx             on public.calls (lead_id, called_at desc);
create index if not exists documents_client_idx       on public.documents (client_id, uploaded_at desc);
create index if not exists invoices_client_idx        on public.invoices (client_id, issue_date desc);
create index if not exists email_logs_lead_idx        on public.email_logs (lead_id, sent_at desc);

-- ---------------------------------------------------------------------------
-- Durable background job records (acceptance 10)
-- ---------------------------------------------------------------------------
-- A job is identified by its idempotency key, not by the invocation. A retried
-- or duplicated Edge Function run inserts the same key, hits the unique index,
-- and does no CRM mutation the second time. This is what makes an at-least-once
-- scheduler safe against double-applying follow-up state.

create table if not exists public.job_runs (
  id              bigint generated by default as identity primary key,
  job             text not null,
  idempotency_key text not null,
  status          text not null default 'running',
  detail          jsonb not null default '{}'::jsonb,
  started_at      timestamptz not null default now(),
  finished_at     timestamptz,
  constraint job_runs_status_known check (status in ('running', 'done', 'failed', 'skipped'))
);

create unique index if not exists job_runs_idempotency_key on public.job_runs (job, idempotency_key);

-- ---------------------------------------------------------------------------
-- RLS: owner-only on every table
-- ---------------------------------------------------------------------------

do $$
declare
  t text;
begin
  for t in
    select unnest(array[
      'leads', 'clients', 'calls', 'email_templates', 'email_logs',
      'documents', 'invoices', 'job_runs'
    ])
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('alter table public.%I force row level security', t);
    execute format('drop policy if exists owner_all on public.%I', t);
    -- Single policy for all four verbs. using() gates read/update/delete,
    -- with check() gates insert/update, so a non-owner can neither see a row
    -- nor write one.
    execute format(
      'create policy owner_all on public.%I for all to authenticated
         using (public.is_owner()) with check (public.is_owner())', t
    );
    -- anon gets nothing. Revoking the grant means an unauthenticated API call
    -- is refused at the privilege layer, before RLS is even consulted.
    execute format('revoke all on public.%I from anon', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end $$;

revoke all on public.app_owner from anon;
grant select on public.app_owner to authenticated;

-- Identity sequences are owned by the tables; authenticated needs usage to
-- insert without supplying an id.
do $$
declare
  s text;
begin
  for s in
    select quote_ident(sequence_schema) || '.' || quote_ident(sequence_name)
    from information_schema.sequences where sequence_schema = 'public'
  loop
    execute format('revoke all on sequence %s from anon', s);
    execute format('grant usage, select on sequence %s to authenticated', s);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Post-apply verification and schema-cache reload
-- ---------------------------------------------------------------------------

-- Fail loudly if this migration did not actually produce what the client
-- requires. Without this, a partial apply (an aborted SQL-editor paste, a
-- statement skipped after an error) leaves a project that looks migrated but
-- answers 404 on the first login — the 2026-11-06 production failure, where
-- the live site reported
--   Could not find the table 'public.app_owner' in the schema cache
-- after a successful sign-in. An error here is far cheaper than that.
do $$
declare
  missing text[] := '{}';
  t text;
begin
  foreach t in array array[
    'app_owner', 'leads', 'clients', 'calls',
    'email_templates', 'email_logs', 'documents', 'invoices', 'job_runs'
  ] loop
    if to_regclass('public.' || quote_ident(t)) is null then
      missing := missing || t;
    end if;
  end loop;

  if array_length(missing, 1) is not null then
    raise exception
      'migration incomplete: missing table(s): %. Re-run 0001_schema.sql in full.',
      array_to_string(missing, ', ');
  end if;

  -- The RLS gate itself. If app_owner exists but is_owner() does not, every
  -- policy that calls it fails at query time instead of at migration time.
  if to_regprocedure('public.is_owner()') is null then
    raise exception 'migration incomplete: public.is_owner() is missing. Re-run 0001_schema.sql in full.';
  end if;

  -- RLS off on any CRM table would mean a signed-in non-owner reads
  -- everything. Verify, do not assume, since it is enabled in a loop above.
  for t in
    select c.relname
    from pg_class c
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public'
      and c.relkind = 'r'
      and c.relname in (
        'app_owner', 'leads', 'clients', 'calls',
        'email_templates', 'email_logs', 'documents', 'invoices', 'job_runs'
      )
      and not c.relrowsecurity
  loop
    raise exception 'migration incomplete: row level security is disabled on public.%', t;
  end loop;

  raise notice 'GapVera schema verified: 9 tables, is_owner() present, RLS enabled on all.';
  raise notice 'Next: grant ownership (see supabase/README.md step 5) — until then every table correctly returns zero rows.';
end $$;

-- PostgREST serves from a cached introspection of the schema. It listens for
-- this signal to re-read it. Supabase normally triggers a reload via DDL event
-- triggers, but that is not guaranteed for every apply path, and a stale cache
-- is indistinguishable at the API from a table that was never created: both
-- return 404 PGRST205. Asking explicitly costs nothing and removes the
-- ambiguity.
notify pgrst, 'reload schema';
