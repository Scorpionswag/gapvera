-- GapVera zero-cost hosted schema.
--
-- Design contract (locked, see handoff/zero-cost/decisions.md):
--   * One owner identity. There is no multi-tenancy and no public signup.
--   * Every table is RLS-protected and FAILS CLOSED: access requires a row in
--     app_owner matching auth.uid(). An empty app_owner table means nobody can
--     read anything, which is the correct posture for a misconfigured project.
--   * The browser only ever holds the anon/publishable key. It is not a secret
--     on its own; RLS is what protects the data. The service_role key is never
--     shipped to the client and never stored in this repo.
--   * IDs stay bigint and preserve the original SQLite integer ids so the
--     migrated copy reconciles 1:1 against the preserved export.

-- ---------------------------------------------------------------------------
-- Owner registry + gate
-- ---------------------------------------------------------------------------

create table if not exists public.app_owner (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  email      text not null,
  created_at timestamptz not null default now()
);

alter table public.app_owner enable row level security;

-- The gate. SECURITY DEFINER so policies can consult app_owner without the
-- caller needing read access to it; STABLE so Postgres evaluates it once per
-- statement instead of once per row. search_path is pinned because a
-- SECURITY DEFINER function with a caller-controlled search_path is a
-- privilege-escalation primitive.
create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = public, pg_catalog
as $$
  select exists (
    select 1 from public.app_owner o where o.user_id = auth.uid()
  );
$$;

revoke all on function public.is_owner() from public;
grant execute on function public.is_owner() to authenticated;

-- The owner may read its own registry row (so the client can confirm access)
-- but may never insert, update, or delete it. Promotion to owner happens only
-- through a privileged path (SQL editor / service role), never from the app.
drop policy if exists app_owner_select_self on public.app_owner;
create policy app_owner_select_self
  on public.app_owner for select
  to authenticated
  using (user_id = auth.uid());

