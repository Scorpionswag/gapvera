-- status carries 'draft' in the zero-cost baseline: automated SMTP is disabled,
-- so an entry here records a composed message, never a claim that mail was sent.
create table if not exists public.email_logs (
  id            bigint generated by default as identity primary key,
  lead_id       bigint references public.leads (id) on delete set null,
  template_id   bigint references public.email_templates (id) on delete set null,
  to_email      text not null default '',
  subject       text not null default '',
  body          text not null default '',
  status        text not null default 'draft',
  scheduled_for text not null default '',
  sent_at       text not null default to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI:SS')
);

create table if not exists public.documents (
  id          bigint generated by default as identity primary key,
